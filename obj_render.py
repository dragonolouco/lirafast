"""Small deterministic OBJ renderer and parametric mesh generator.

It uses matplotlib only for the final rasterization. The OBJ parser and the
procedural mesh generation are plain Python, so the structural part can later
move to a lighter native/mobile kernel.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path


@dataclass
class Mesh:
    vertices: list[tuple[float, float, float]]
    faces: list[tuple[int, int, int]]
    objects: list[str]

    @property
    def bounds(self) -> tuple[tuple[float, float, float], tuple[float, float, float]]:
        if not self.vertices:
            raise ValueError("mesh has no vertices")
        mins = tuple(min(v[i] for v in self.vertices) for i in range(3))
        maxs = tuple(max(v[i] for v in self.vertices) for i in range(3))
        return mins, maxs


def read_obj(path: str | Path) -> Mesh:
    vertices: list[tuple[float, float, float]] = []
    faces: list[tuple[int, int, int]] = []
    objects: list[str] = []
    for raw in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if parts[0] == "v" and len(parts) >= 4:
            vertices.append((float(parts[1]), float(parts[2]), float(parts[3])))
        elif parts[0] == "o" and len(parts) >= 2:
            objects.append(" ".join(parts[1:]))
        elif parts[0] == "f" and len(parts) >= 4:
            indices = []
            for token in parts[1:]:
                index = int(token.split("/")[0])
                indices.append(index if index > 0 else len(vertices) + index + 1)
            for i in range(1, len(indices) - 1):
                faces.append((indices[0] - 1, indices[i] - 1, indices[i + 1] - 1))
    if not vertices or not faces:
        raise ValueError("OBJ must contain at least one vertex and one face")
    if any(index < 0 or index >= len(vertices) for face in faces for index in face):
        raise ValueError("OBJ contains a face index outside its vertex list")
    return Mesh(vertices, faces, objects)


def write_obj(mesh: Mesh, path: str | Path) -> None:
    out = ["# Generated by LiraFast structural object generator"]
    for vertex in mesh.vertices:
        out.append("v " + " ".join(f"{value:.8f}" for value in vertex))
    for a, b, c in mesh.faces:
        out.append(f"f {a + 1} {b + 1} {c + 1}")
    Path(path).write_text("\n".join(out) + "\n", encoding="utf-8")


def make_cube(size: float = 1.0) -> Mesh:
    s = size / 2
    vertices = [(-s, -s, -s), (s, -s, -s), (s, s, -s), (-s, s, -s),
                (-s, -s, s), (s, -s, s), (s, s, s), (-s, s, s)]
    faces = [(0, 1, 2), (0, 2, 3), (4, 6, 5), (4, 7, 6),
             (0, 4, 5), (0, 5, 1), (3, 2, 6), (3, 6, 7),
             (0, 3, 7), (0, 7, 4), (1, 5, 6), (1, 6, 2)]
    return Mesh(vertices, faces, ["cube"])


def make_heightmap(rows: int = 32, cols: int = 32, scale: float = 2.0) -> Mesh:
    """Create a small map-like surface from a deterministic formula."""
    import math
    vertices = []
    for row in range(rows):
        y = (row / (rows - 1) - 0.5) * scale
        for col in range(cols):
            x = (col / (cols - 1) - 0.5) * scale
            z = 0.18 * math.sin(x * 5.0) * math.cos(y * 4.0)
            vertices.append((x, y, z))
    faces = []
    for row in range(rows - 1):
        for col in range(cols - 1):
            a = row * cols + col
            b, c, d = a + 1, a + cols, a + cols + 1
            faces.extend([(a, b, d), (a, d, c)])
    return Mesh(vertices, faces, ["heightmap"])


def render_obj(mesh: Mesh, output: str | Path, *, elevation: float = 20, azimuth: float = -65,
               dpi: int = 150, title: str | None = None) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from mpl_toolkits.mplot3d.art3d import Poly3DCollection

    polygons = [[mesh.vertices[index] for index in face] for face in mesh.faces]
    fig = plt.figure(figsize=(10, 8), dpi=dpi)
    ax = fig.add_subplot(111, projection="3d")
    collection = Poly3DCollection(polygons, facecolor="#63b3ed", edgecolor="#15324b",
                                  linewidths=0.08, alpha=0.96)
    ax.add_collection3d(collection)
    mins, maxs = mesh.bounds
    centers = [(mins[i] + maxs[i]) / 2 for i in range(3)]
    radius = max(maxs[i] - mins[i] for i in range(3)) / 2 or 1
    ax.set_xlim(centers[0] - radius, centers[0] + radius)
    ax.set_ylim(centers[1] - radius, centers[1] + radius)
    ax.set_zlim(centers[2] - radius, centers[2] + radius)
    ax.set_box_aspect((1, 1, 1))
    ax.view_init(elev=elevation, azim=azimuth)
    ax.set_axis_off()
    if title:
        ax.set_title(title)
    fig.tight_layout(pad=0)
    fig.savefig(output, bbox_inches="tight", pad_inches=0.05)
    plt.close(fig)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Render and generate simple LiraFast OBJ models")
    sub = parser.add_subparsers(dest="command", required=True)
    render = sub.add_parser("render", help="render an existing OBJ to PNG")
    render.add_argument("obj")
    render.add_argument("output")
    render.add_argument("--elevation", type=float, default=20)
    render.add_argument("--azimuth", type=float, default=-65)
    cube = sub.add_parser("cube", help="generate and render a cube")
    cube.add_argument("obj")
    cube.add_argument("png")
    cube.add_argument("--size", type=float, default=1.0)
    grid = sub.add_parser("heightmap", help="generate and render a procedural map surface")
    grid.add_argument("obj")
    grid.add_argument("png")
    grid.add_argument("--rows", type=int, default=32)
    grid.add_argument("--cols", type=int, default=32)
    args = parser.parse_args(argv)
    if args.command == "render":
        mesh = read_obj(args.obj)
        render_obj(mesh, args.output, elevation=args.elevation, azimuth=args.azimuth,
                   title=Path(args.obj).stem)
    elif args.command == "cube":
        mesh = make_cube(args.size)
        write_obj(mesh, args.obj)
        render_obj(mesh, args.png, title="LiraFast procedural cube")
    else:
        mesh = make_heightmap(args.rows, args.cols)
        write_obj(mesh, args.obj)
        render_obj(mesh, args.png, title="LiraFast procedural heightmap")


if __name__ == "__main__":
    main()
